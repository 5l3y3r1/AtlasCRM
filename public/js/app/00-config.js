function t(key, fallback) {
    if (I18N[key] && I18N[key][currentLang]) return I18N[key][currentLang];
    return fallback != null ? fallback : key;
}
function applyLang() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (I18N[key] && I18N[key][currentLang]) el.textContent = I18N[key][currentLang];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (I18N[key] && I18N[key][currentLang]) el.placeholder = I18N[key][currentLang];
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (I18N[key] && I18N[key][currentLang]) el.title = I18N[key][currentLang];
    });
    document.documentElement.lang = currentLang;
    // A few pieces of chrome are set once at login (JS textContent, not data-i18n) —
    // refresh them here so a language switch actually changes them too.
    try {
        const roleEl = document.getElementById('user-role');
        if (roleEl && window.currentUser && window.roleNames) roleEl.textContent = roleNames[currentUser.role] || currentUser.role;
        const greetEl = document.getElementById('dashboard-greeting');
        if (greetEl && window.currentUser && typeof getGreeting === 'function') greetEl.textContent = getGreeting() + ', ' + currentUser.first_name + '!';
    } catch (e) {}
    ['ka','en','ru'].forEach(lng => {
        const btn = document.getElementById('lang-' + lng);
        if (!btn) return;
        btn.style.background = currentLang === lng ? 'var(--brand)' : 'var(--surface-2)';
        btn.style.color      = currentLang === lng ? '#fff' : 'var(--text-muted)';
    });
}
function setLang(lang) {
    currentLang = lang;
    try { localStorage.setItem('atlas_lang', lang); } catch(e){}
    applyLang();
    // Re-render the active page so dynamically built content picks up the language.
    try { if (typeof navigateTo === 'function' && currentPage) navigateTo(currentPage); } catch(e){}
}

